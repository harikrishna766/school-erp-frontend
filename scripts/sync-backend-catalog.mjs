#!/usr/bin/env node
/**
 * Vendors the backend's access catalog (modules, permission matrix, role templates) into
 * src/mocks/data/backend-catalog/ so mock users get exactly the permissions the real
 * backend would grant. Used by MSW handlers and tests only, never by app code (the app
 * learns permissions from GET /me/access at runtime).
 *
 *   BACKEND_DIR=../school-erp-backend npm run catalog:sync
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const backend = process.env.BACKEND_DIR ?? '../school-erp-backend';
const src = join(backend, 'src/modules/access/catalog');
const out = 'src/mocks/data/backend-catalog';
mkdirSync(out, { recursive: true });

const header = (file) =>
  `// GENERATED by scripts/sync-backend-catalog.mjs from school-erp-backend/${file}.\n` +
  `// Do not edit; re-run \`npm run catalog:sync\` when the backend catalog changes.\n`;

for (const name of ['modules.catalog.ts', 'permissions.catalog.ts', 'roles.catalog.ts']) {
  let code = readFileSync(join(src, name), 'utf8');
  // The only backend-internal import: the Prisma DataScope enum.
  code = code.replace(
    /import type \{ DataScope \} from '[^']+';/,
    "import type { DataScope } from '../../../app/core/access/access.model';",
  );
  writeFileSync(join(out, name), header(`src/modules/access/catalog/${name}`) + code);
  console.log(`catalog:sync: ${name}`);
}
